FILE_PATH = 'static/js/translations.js'

def main():
    with open(FILE_PATH, 'r', encoding='utf-8') as f:
        content = f.read()

    langs = ['en', 'hi', 'pa', 'bn', 'mr', 'gu', 'te', 'ta', 'kn', 'ml']
    
    # In KRISHI_TRANSLATIONS, insert keys after each lang header
    for lang in langs:
        target_marker = f'"{lang}": {{'
        # Find position after target_marker in KRISHI_TRANSLATIONS (the second occurrence in file)
        pos = content.find('const KRISHI_TRANSLATIONS = {')
        if pos == -1:
            print("Could not find KRISHI_TRANSLATIONS")
            return
        
        idx = content.find(target_marker, pos)
        if idx != -1:
            insert_pos = idx + len(target_marker)
            lines_to_add = []
            for k, trans_dict in NEW_KEYS.items():
                val = trans_dict.get(lang, trans_dict['en']).replace("'", "\\'")
                lines_to_add.append(f'\n    "{k}": "{val}",')
            
            insert_str = "".join(lines_to_add)
            content = content[:insert_pos] + insert_str + content[insert_pos:]
            print(f"Injected {len(NEW_KEYS)} keys for {lang} in KRISHI_TRANSLATIONS")

    with open(FILE_PATH, 'w', encoding='utf-8') as f:
        f.write(content)

    print("Finished updating static/js/translations.js successfully!")

if __name__ == '__main__':
    main()
