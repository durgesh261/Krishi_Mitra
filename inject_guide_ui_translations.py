def inject_guide_keys():
    with open("static/js/translations.js", "r", encoding="utf-8") as f:
        content = f.read()

    # In KRISHI_TRANSLATIONS dictionary, each language has a dictionary of keys
    # Let's find "const KRISHI_TRANSLATIONS = {"
    for lang in ["en", "hi", "pa", "bn", "mr", "gu", "te", "ta", "kn", "ml"]:
        pattern = rf'"{lang}":\s*\{{'
        match = re.search(pattern, content)
        if match:
            insert_pos = match.end()
            additions = []
            for k, val_dict in GUIDE_UI_KEYS.items():
                val = val_dict.get(lang, val_dict["en"]).replace('"', '\\"')
                additions.append(f'\n    "{k}": "{val}",')
            add_str = "".join(additions)
            content = content[:insert_pos] + add_str + content[insert_pos:]
            print(f"Injected UI keys for language: {lang}")

    with open("static/js/translations.js", "w", encoding="utf-8") as f:
        f.write(content)
    print("translations.js successfully updated with guide UI keys!")

if __name__ == "__main__":
    inject_guide_keys()
