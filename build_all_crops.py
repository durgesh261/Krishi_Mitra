def write_crop_guides_csv():
    fieldnames = [
        "crop", "category", "crop_name", "sub_category", "season", "soil_type",
        "watering_schedule", "fertilizer_plan", "duration_days",
        "ideal_temp_min", "ideal_temp_max", "ideal_humidity_min", "ideal_humidity_max",
        "expected_yield", "pest_disease_advisory"
    ]
    
    with open("train/dataset/crop_guides.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in CROPS_DATA:
            writer.writerow(row)
            
    print(f"Successfully wrote train/dataset/crop_guides.csv with {len(CROPS_DATA)} crops!")

if __name__ == "__main__":
    write_crop_guides_csv()
